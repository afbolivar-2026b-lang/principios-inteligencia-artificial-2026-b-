// Prueba de punta a punta de lo imprescindible (Playwright): editar, borrar, filtros, presupuestos con alertas, análisis,
// categorías, tema, respaldo con y sin clave, recuperar en un "celular nuevo", modo sin internet y pantalla ancha.
// Se corre con la app armada y en marcha:  cd app && npm run build && npx vite preview --port 4173
//   node e2e/imprescindibles.cjs   (necesita: npm i -g playwright; escribe unos archivos de respaldo de prueba en la carpeta actual)
const { chromium } = require('playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const URL = 'http://localhost:4173/'
const paso = (t) => console.log('✔', t)
const nuevoContexto = (b, extra = {}) => b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, locale: 'es-CO', timezoneId: 'America/Bogota', acceptDownloads: true, ...extra })
const sinDesborde = (p) => p.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)

;(async () => {
  const b = await chromium.launch()
  const ctx = await nuevoContexto(b)
  const p = await ctx.newPage()
  const errores = []
  p.on('console', (m) => { if (m.type() === 'error') errores.push(m.text()) })
  p.on('pageerror', (e) => errores.push(String(e)))
  await p.goto(URL + '?demo')
  await p.getByText('Actividad reciente').waitFor()

  // ---------- editar y borrar ----------
  await p.getByRole('button', { name: /Editar (gasto|ingreso)\. Almuerzo/ }).click()
  await p.getByRole('dialog', { name: 'Editar gasto' }).waitFor()
  assert.equal(await p.locator('#monto').inputValue(), '$18.000')
  assert.equal(await p.locator('#descripcion').inputValue(), 'Almuerzo')
  assert.equal(await p.getByRole('radio', { name: 'Comida' }).getAttribute('aria-checked'), 'true')
  await p.locator('#monto').fill('20000')
  await p.getByRole('button', { name: 'Guardar cambios' }).click()
  await p.getByRole('status').getByText('Cambios guardados').waitFor()
  await p.getByRole('button', { name: /Editar (gasto|ingreso)\. Almuerzo.*20\.000/ }).waitFor()
  await p.getByRole('button', { name: 'Deshacer' }).click()
  await p.getByRole('button', { name: /Editar (gasto|ingreso)\. Almuerzo.*18\.000/ }).waitFor()
  paso('editar un gasto y deshacer la edición')

  await p.getByRole('button', { name: /Editar (gasto|ingreso)\. Bus/ }).click()
  await p.getByRole('button', { name: 'Borrar', exact: true }).click()
  await p.getByText('¿Borrar este gasto?').waitFor()
  await p.getByRole('button', { name: 'No', exact: true }).click()
  await p.getByRole('button', { name: 'Guardar cambios' }).waitFor()
  await p.getByRole('button', { name: 'Borrar', exact: true }).click()
  await p.getByRole('button', { name: 'Sí, borrar' }).click()
  await p.getByRole('status').getByText('Movimiento borrado').waitFor()
  assert.equal(await p.getByRole('button', { name: /Editar (gasto|ingreso)\. Bus/ }).count(), 0)
  await p.getByRole('button', { name: 'Deshacer' }).click()
  await p.getByRole('button', { name: /Editar (gasto|ingreso)\. Bus/ }).waitFor()
  paso('borrar pide confirmación, "No" cancela, y "Deshacer" lo trae de vuelta')

  // ---------- lista completa y filtros ----------
  await p.getByRole('button', { name: 'Ver todo' }).click()
  await p.getByRole('heading', { name: 'Movimientos' }).waitFor()
  await p.getByText(/^12 movimientos/).waitFor()
  await p.screenshot({ path: 'n-movimientos.png' })
  await p.getByRole('radio', { name: 'Ingresos' }).click()
  await p.getByText(/^1 movimiento ·/).waitFor()
  await p.getByRole('radio', { name: 'Todos' }).click()
  await p.getByLabel('Categoría').selectOption({ label: 'Comida' })
  await p.getByText(/^3 movimientos/).waitFor()
  await p.getByLabel('Categoría').selectOption({ label: 'Todas las categorías' })
  await p.getByLabel('Buscar').fill('CINE')
  await p.getByText(/^1 movimiento ·/).waitFor()
  await p.getByLabel('Buscar').fill('comida')
  await p.getByText(/^3 movimientos/).waitFor()
  await p.getByLabel('Buscar').fill('zzz')
  await p.getByText('No hay movimientos con estos filtros').waitFor()
  await p.getByRole('button', { name: 'Quitar filtros' }).click()
  await p.getByText(/^12 movimientos/).waitFor()
  paso('lista completa: filtra por tipo, categoría y búsqueda (sin importar mayúsculas), y quita filtros')
  await p.getByRole('button', { name: 'Mes anterior' }).click()
  await p.getByText(/^4 movimientos/).waitFor()
  for (let i = 0; i < 5; i++) await p.getByRole('button', { name: 'Mes anterior' }).click()
  await p.getByText('No hay movimientos en este mes').waitFor()
  assert.equal(await p.getByRole('button', { name: 'Mes siguiente' }).isDisabled(), false)
  for (let i = 0; i < 6; i++) await p.getByRole('button', { name: 'Mes siguiente' }).click()
  assert.equal(await p.getByRole('button', { name: 'Mes siguiente' }).isDisabled(), true)
  paso('se puede ir al mes anterior y no pasarse del mes actual')
  await p.getByRole('button', { name: 'Volver' }).click()

  // ---------- presupuestos ----------
  await p.getByRole('button', { name: 'Presupuestos', exact: true }).click()
  await p.getByRole('heading', { name: 'Presupuestos' }).waitFor()
  await p.getByText(/presupuestados en 4 categorías/).waitFor()
  await p.getByText('Te pasaste por $5.200').first().waitFor()
  await p.getByText('Vas en el 95 % · te quedan $7.500').waitFor()
  await p.getByRole('button', { name: /Cambiar límite\. Salud/ }).click()
  await p.getByRole('button', { name: 'Guardar límite' }).click()
  await p.getByText('Escribe un límite mayor a 0').waitFor()
  await p.getByLabel('Cuánto quieres gastar al mes').fill('50000')
  await p.getByRole('radio', { name: '90 %' }).click()
  await p.getByRole('button', { name: 'Guardar límite' }).click()
  await p.getByRole('status').getByText('Límite de Salud: $50.000 al mes').waitFor()
  await p.getByText(/presupuestados en 5 categorías/).waitFor()
  await p.getByRole('button', { name: /Cambiar límite\. Salud/ }).click()
  await p.getByRole('button', { name: 'Quitar', exact: true }).click()
  await p.getByRole('button', { name: 'No', exact: true }).click()
  await p.getByRole('button', { name: 'Guardar límite' }).waitFor()
  await p.getByRole('button', { name: 'Quitar', exact: true }).click()
  await p.getByRole('button', { name: 'Sí, quitar' }).click()
  await p.getByText(/presupuestados en 4 categorías/).waitFor()
  paso('presupuestos de ejemplo con alertas; poner un límite nuevo, cancelar el quitarlo con "No" (sin cerrar) y quitarlo de verdad')

  const anotar = async (monto, desc) => {
    await p.getByRole('button', { name: 'Inicio', exact: true }).click()
    await p.getByRole('button', { name: 'Agregar movimiento' }).click()
    await p.locator('#monto').fill(monto)
    await p.getByRole('radio', { name: 'Comida' }).click()
    await p.locator('#descripcion').fill(desc)
    await p.getByRole('button', { name: 'Guardar', exact: true }).click()
    await p.getByRole('dialog').waitFor({ state: 'detached' })
  }
  await anotar('10000', 'Cena')
  await p.getByRole('status').getByText('Guardado · Comida va en el 92 % de su presupuesto').waitFor()
  await p.getByText('te pasaste por $5.200').waitFor()
  await p.getByText('vas en el 95 % de tu presupuesto').waitFor()
  await p.getByText('y 1 categoría más en alerta').waitFor()
  paso('al pasar el 80 % avisa en el momento de guardar; Inicio muestra las 2 alertas más graves y cuenta las demás')
  await anotar('10000', 'Otra cena')
  await p.getByRole('status').getByText('Guardado · Te pasaste en Comida por $5.000').waitFor()
  await p.getByText('te pasaste por $5.000').waitFor()
  await p.screenshot({ path: 'n-inicio-aviso.png' })
  paso('al pasarse del límite lo dice con el valor exacto: $5.000')

  // ---------- análisis ----------
  await p.getByRole('button', { name: 'Análisis', exact: true }).click()
  await p.getByRole('img', { name: /^Gastos de .*: \$/ }).waitFor()
  await p.getByRole('heading', { name: 'En qué se fue la plata' }).waitFor()
  assert.ok((await p.locator('section ul li').count()) >= 4)
  assert.ok((await p.getByText(/^\d+ %$/).count()) >= 4)
  await p.screenshot({ path: 'n-analisis.png', fullPage: true })
  await p.getByRole('button', { name: 'Mes anterior' }).click()
  await p.getByText(/Gastaste/).waitFor()
  for (let i = 0; i < 5; i++) await p.getByRole('button', { name: 'Mes anterior' }).click()
  await p.getByText(/No hay gastos en/).waitFor()
  paso('análisis: gráfico de torta con porcentajes, barras de 6 meses y mes sin gastos')

  // ---------- categorías ----------
  await p.getByRole('button', { name: 'Ajustes', exact: true }).last().click()
  await p.getByRole('heading', { name: 'Ajustes' }).waitFor()
  await p.getByRole('button', { name: 'Categorías' }).click()
  await p.getByRole('button', { name: 'Nueva categoría' }).click()
  await p.getByLabel('Nombre').fill('Mascotas')
  await p.getByRole('radio', { name: 'Mascota' }).click()
  await p.getByRole('button', { name: 'Guardar', exact: true }).click()
  await p.getByRole('status').getByText('Creaste "Mascotas"').waitFor()
  await p.getByRole('button', { name: 'Nueva categoría' }).click()
  await p.getByLabel('Nombre').fill('mascotas')
  await p.getByRole('button', { name: 'Guardar', exact: true }).click()
  await p.getByText('Ya tienes una categoría con ese nombre').waitFor()
  await p.getByRole('button', { name: 'Cerrar' }).click()
  await p.screenshot({ path: 'n-categorias.png' })
  await p.getByRole('button', { name: 'Mascotas' }).click()
  await p.getByRole('button', { name: 'Archivar' }).click()
  await p.getByRole('status').getByText(/Archivaste "Mascotas"/).waitFor()
  await p.getByText('Archivada').waitFor()
  await p.getByRole('button', { name: 'Volver' }).click()
  await p.getByRole('button', { name: 'Inicio', exact: true }).click()
  await p.getByRole('button', { name: 'Agregar movimiento' }).click()
  assert.equal(await p.getByRole('radio', { name: 'Mascotas' }).count(), 0)
  await p.keyboard.press('Escape')
  paso('categorías: crear, no repetir nombre, archivar (desaparece del formulario)')

  // ---------- tema ----------
  await p.getByRole('button', { name: 'Ajustes', exact: true }).last().click()
  await p.getByRole('radio', { name: 'Oscuro' }).click()
  await p.waitForFunction(() => document.documentElement.dataset.theme === 'oscuro')
  await p.reload({ waitUntil: 'domcontentloaded' })
  assert.equal(await p.evaluate(() => document.documentElement.dataset.theme), 'oscuro') // ya antes de que cargue la app: sin parpadeo
  await p.getByRole('heading', { name: 'Ajustes' }).waitFor().catch(() => {})
  await p.getByRole('button', { name: 'Ajustes', exact: true }).last().click()
  await p.getByRole('radio', { name: 'Automático' }).click()
  await p.waitForFunction(() => !document.documentElement.dataset.theme)
  paso('tema oscuro manual: se recuerda y se aplica antes de pintar; Automático lo quita')

  // ---------- respaldo ----------
  await p.getByText('Todavía no has hecho un respaldo').waitFor()
  const [d1] = await Promise.all([p.waitForEvent('download'), p.getByRole('button', { name: 'Descargar respaldo' }).click()])
  const ruta1 = await d1.path()
  const json1 = JSON.parse(fs.readFileSync(ruta1, 'utf8'))
  assert.equal(json1.app, 'nova-gastos')
  assert.ok(json1.movimientos.length >= 28)
  assert.match(d1.suggestedFilename(), /^nova-respaldo-\d{4}-\d{2}-\d{2}\.json$/)
  await p.getByText('Último respaldo: hoy').waitFor()
  paso(`respaldo sin clave descargado (${json1.movimientos.length} movimientos) y "Último respaldo: hoy"`)

  await p.getByLabel('Clave para proteger el archivo (opcional)').fill('secreta123')
  const [d2] = await Promise.all([p.waitForEvent('download'), p.getByRole('button', { name: 'Descargar respaldo' }).click()])
  const texto2 = fs.readFileSync(await d2.path(), 'utf8')
  assert.ok(texto2.includes('nova_cifrado'))
  assert.ok(!texto2.includes('Almuerzo') && !texto2.includes('Comida'))
  fs.writeFileSync('respaldo-con-clave.json', texto2)
  fs.writeFileSync('respaldo-sin-clave.json', JSON.stringify(json1))
  paso('respaldo con clave: el archivo no deja ver ni "Almuerzo" ni "Comida"')
  await p.screenshot({ path: 'n-ajustes.png', fullPage: true })

  // sin internet: todo sigue funcionando
  await p.evaluate(() => navigator.serviceWorker.ready)
  await p.reload(); await p.getByRole('heading', { name: 'Inicio' }).waitFor({ state: 'attached' })
  await ctx.setOffline(true)
  await p.reload()
  await p.getByText('Actividad reciente').waitFor()
  await p.getByRole('button', { name: 'Presupuestos', exact: true }).click()
  await p.getByRole('button', { name: /Cambiar límite\. Comida/ }).waitFor()
  await p.getByRole('button', { name: 'Análisis', exact: true }).click()
  await p.getByRole('img', { name: /^Gastos de/ }).waitFor()
  paso('SIN INTERNET: presupuestos y análisis funcionan')
  await ctx.setOffline(false)

  // ---------- "celular nuevo": recuperar los respaldos ----------
  const ctx2 = await nuevoContexto(b)
  const q = await ctx2.newPage()
  q.on('pageerror', (e) => errores.push('celular nuevo: ' + String(e)))
  await q.goto(URL)
  await q.getByText('Todavía no has anotado nada').waitFor()
  await q.getByRole('button', { name: 'Ajustes', exact: true }).last().click()

  await q.locator('input[type=file]').setInputFiles('respaldo-con-clave.json')
  await q.getByText('Este respaldo tiene clave').waitFor()
  await q.getByLabel('Este respaldo tiene clave').fill('mala-clave')
  await q.getByRole('button', { name: 'Abrir' }).click()
  await q.getByText('La clave no es correcta').waitFor()
  await q.getByLabel('Este respaldo tiene clave').fill('secreta123')
  await q.getByRole('button', { name: 'Abrir' }).click()
  await q.getByText(/^Respaldo del .*: \d+ movimientos/).waitFor()
  await q.getByRole('button', { name: 'Recuperar', exact: true }).click()
  await q.getByRole('status').getByText(/Se sumaron \d+ movimientos nuevos/).waitFor()
  paso('celular nuevo: clave mala se rechaza, clave buena abre, y "Sumar" trae los datos')

  await q.locator('input[type=file]').setInputFiles('respaldo-sin-clave.json')
  await q.getByText(/^Respaldo del/).waitFor()
  await q.getByRole('radio', { name: 'Reemplazar todo lo que tengo' }).click()
  await q.getByText('Esto borra tus datos actuales').waitFor()
  await q.getByRole('button', { name: 'Sí, reemplazar todo' }).click()
  await q.getByRole('status').getByText(/Recuperaste \d+ movimientos/).waitFor()
  paso('"Reemplazar" avisa que borra lo actual y lo hace solo tras confirmar')

  fs.writeFileSync('basura.json', '{"app":"otra-cosa"}')
  await q.locator('input[type=file]').setInputFiles('basura.json')
  await q.getByText('El archivo no es un respaldo de Nova').waitFor()
  await q.getByRole('button', { name: 'Cerrar' }).click()
  paso('un archivo que no es de Nova se rechaza con un mensaje claro')

  await q.getByRole('button', { name: 'Inicio', exact: true }).click()
  await q.getByRole('button', { name: /Editar (gasto|ingreso)\. Almuerzo/ }).waitFor()
  await q.getByText('Haz un respaldo.').waitFor()
  paso('en el celular nuevo se ven los datos y la app recuerda hacer un respaldo')

  // ---------- pantalla ancha y sin desbordes ----------
  for (const [ancho, alto] of [[390, 844], [1440, 900]]) {
    const c = await nuevoContexto(b, { viewport: { width: ancho, height: alto } })
    const r = await c.newPage()
    await r.goto(URL + '?demo'); await r.getByText('Actividad reciente').waitFor()
    for (const t of ['Inicio', 'Análisis', 'Presupuestos', 'Metas', 'Ajustes']) {
      await r.getByRole('button', { name: t, exact: true }).last().click()
      await r.waitForTimeout(150)
      assert.equal(await sinDesborde(r), true, `desborde horizontal en ${t} a ${ancho}px`)
    }
    if (ancho === 1440) await r.screenshot({ path: 'n-ancho.png' })
    await c.close()
  }
  paso('sin desborde horizontal en ninguna pestaña a 390 px y a 1440 px')

  console.log(errores.length ? `⚠ errores de consola: ${errores.join(' | ')}` : '✔ sin errores en la consola')
  await b.close()
})().catch((e) => { console.error('✘ FALLÓ:', e.message.split('\n').slice(0, 8).join('\n')); process.exit(1) })
